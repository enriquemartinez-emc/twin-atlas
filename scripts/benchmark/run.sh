#!/usr/bin/env bash
# Seeds a benchmark database and measures the read queries with and without the GiST index.
#   scripts/benchmark/run.sh [points=1000000] [polygons=200000] [runs=200]
# Needs: docker compose, Java 25 (JAVA_HOME or on PATH), Node 20+. Uses its own database
# (twinatlas_bench) and port 18080, so it does not touch your development data or server.
# Results: docs/benchmark/results.md and docs/benchmark/plans.txt
set -euo pipefail

POINTS=${1:-1000000}
POLYGONS=${2:-200000}
RUNS=${3:-200}
NOINDEX_RUNS=$(( RUNS / 4 > 20 ? RUNS / 4 : 20 ))

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
HERE="$ROOT/scripts/benchmark"
OUT="$ROOT/docs/benchmark"
DB=twinatlas_bench
PORT=18080
SCENE=00000000-0000-4000-8000-0000000000b1
JAR="$ROOT/server/target/twin-atlas-server-0.0.1-SNAPSHOT.jar"
JAVA=${JAVA_HOME:+$JAVA_HOME/bin/}java
mkdir -p "$OUT"

compose() { docker compose -f "$ROOT/docker-compose.yml" "$@"; }
psqlb() { compose exec -T db psql -U twinatlas -v ON_ERROR_STOP=1 "$@"; }
db_memory() { docker stats --no-stream --format '{{.MemUsage}}' "$(compose ps -q db)"; }

SERVER_PID=""
cleanup() {
  if [ -n "$SERVER_PID" ] && tr '\0' ' ' < "/proc/$SERVER_PID/cmdline" 2>/dev/null | grep -q twin-atlas-server; then
    kill "$SERVER_PID" 2>/dev/null || true
  fi
}
trap cleanup EXIT

echo "1/6 database up"
compose up -d --wait db >/dev/null
psqlb -d postgres -qc "DROP DATABASE IF EXISTS $DB WITH (FORCE)" -c "CREATE DATABASE $DB"

echo "2/6 server on :$PORT (Flyway builds the schema)"
[ -f "$JAR" ] || (cd "$ROOT/server" && ./mvnw -q package -DskipTests -Dspotless.check.skip=true)
DATABASE_URL="jdbc:postgresql://localhost:5432/$DB" "$JAVA" -Xmx512m -jar "$JAR" --server.port=$PORT > "$OUT/.server.log" 2>&1 &
SERVER_PID=$!
for _ in $(seq 1 60); do
  [ "$(curl -s -o /dev/null -w '%{http_code}' "http://localhost:$PORT/actuator/health" || true)" = 200 ] && break
  sleep 2
done

echo "3/6 seeding $POINTS points and $POLYGONS outlines"
SEED_START=$(date +%s)
psqlb -d $DB -q -v points="$POINTS" -v polygons="$POLYGONS" -f - < "$HERE/seed.sql" > "$OUT/.seed.out"
SEED_SECONDS=$(( $(date +%s) - SEED_START ))
MEM_AFTER_SEED=$(db_memory)

{
  echo "# Benchmark results"
  echo
  echo "Generated by \`scripts/benchmark/run.sh $POINTS $POLYGONS $RUNS\` on $(date -u +%Y-%m-%d)."
  echo
  echo "## Machine"
  echo
  echo "- CPUs: $(nproc)"
  echo "- Memory visible to Linux: $(free -m | awk '/Mem:/ {printf "%.1f GiB", $2/1024}')"
  echo "- Memory visible to Docker: $(docker info --format '{{.MemTotal}}' | awk '{printf "%.1f GiB", $1/1073741824}')"
  echo "- Database container limit: 1.5 GiB (see docker-compose.yml). Server heap: 512 MB."
  echo "- $(psqlb -d $DB -At -c "select version()" | cut -d, -f1)"
  echo "- PostGIS $(psqlb -d $DB -At -c "select postgis_version()")"
  echo "- Postgres settings: $(psqlb -d $DB -At -c "select string_agg(name || '=' || setting || coalesce(unit, ''), ', ' order by name) from pg_settings where name in ('shared_buffers','effective_cache_size','work_mem','maintenance_work_mem','max_connections')")"
  echo
  echo "## Data"
  echo
  echo "Seeded in ${SEED_SECONDS} s (indexes in place while inserting). Database container memory right after: ${MEM_AFTER_SEED}."
  echo
  echo '```'
  cat "$OUT/.seed.out"
  echo '```'
  echo
  echo "## API latency"
  echo
} > "$OUT/results.md"

echo "4/6 query plans, with and without the GiST index"
{
  psqlb -d $DB -q -v label="WITH the GiST index (ix_annotation_geom)" -f - < "$HERE/plans.sql"
  psqlb -d $DB -qc "DROP INDEX ix_annotation_geom"
  psqlb -d $DB -q -v label="WITHOUT the GiST index (dropped)" -f - < "$HERE/plans.sql"
  psqlb -d $DB -qc "CREATE INDEX ix_annotation_geom ON annotation USING gist (geom)" -c "ANALYZE annotation"
} > "$OUT/plans.txt"

echo "5/6 API latency with the index ($RUNS runs per operation)"
node "$HERE/api-latency.mjs" "http://localhost:$PORT" "$SCENE" "$RUNS" "With the GiST index" >> "$OUT/results.md"
MEM_AFTER_INDEXED=$(db_memory)

echo "6/6 API latency without the index ($NOINDEX_RUNS runs per operation)"
psqlb -d $DB -qc "DROP INDEX ix_annotation_geom"
node "$HERE/api-latency.mjs" "http://localhost:$PORT" "$SCENE" "$NOINDEX_RUNS" "Without the GiST index" >> "$OUT/results.md"
psqlb -d $DB -qc "CREATE INDEX ix_annotation_geom ON annotation USING gist (geom)" -c "ANALYZE annotation"
MEM_AFTER_NOINDEX=$(db_memory)

{
  echo "## Memory"
  echo
  echo "Database container, sampled after each phase (limit 1.5 GiB): after seeding ${MEM_AFTER_SEED}, after the indexed run ${MEM_AFTER_INDEXED}, after the unindexed run ${MEM_AFTER_NOINDEX}."
  echo "Server process resident memory at the end: $(ps -o rss= -p "$SERVER_PID" | awk '{printf "%.0f MB", $1/1024}')."
} >> "$OUT/results.md"
rm -f "$OUT/.seed.out" "$OUT/.server.log"
echo "done: $OUT/results.md and $OUT/plans.txt"
echo "clean up the benchmark data with: docker compose exec db psql -U twinatlas -d postgres -c 'DROP DATABASE twinatlas_bench WITH (FORCE)'"
